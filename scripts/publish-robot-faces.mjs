#!/usr/bin/env node
/* ==========================================================================
   Publishes the app's tool faces to the website.

     node scripts/publish-robot-faces.mjs
     node scripts/publish-robot-faces.mjs --check

   The art has one source and it is not this script. The playhouse composes the
   robot; scripts/sync-tool-props.mjs photographs him into app/assets/; this
   copies what that produced out to assets/robots/ so the agent wall on the web
   can show the same thing the wall in the app shows. One direction only —
   playhouse → app → web — so there is no second place to edit and no way for
   the two walls to disagree about what "at the console" looks like.

   That matters more than it sounds. The screenshot of the wall on the info
   page sat two generations stale for months because nothing checked it, and
   the only reason anybody noticed was that someone opened it. `--check` is
   here so this set cannot do the same thing quietly.
   ========================================================================== */

import { execFileSync } from 'node:child_process';
import {
  copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const SRC_SCENES = join(REPO, 'app/assets/img/scenes');
const SRC_PROPS = join(REPO, 'app/assets/img/props');
const SRC_MANIFEST = join(REPO, 'app/assets/tool-props.json');

const OUT = join(REPO, 'assets/robots');
const OUT_SCENES = join(OUT, 'scenes');
const OUT_PROPS = join(OUT, 'props');
const OUT_TABLE = join(OUT, 'tool-faces.js');

const manifest = JSON.parse(readFileSync(SRC_MANIFEST, 'utf8'));
const tools = manifest.props ?? {};

/* Every art a row names, plus the lettered block the app falls back to for a
   tool nobody wrote a row for. */
const arts = new Set(Object.values(tools).map((r) => r.art).filter(Boolean));
arts.add('tile');

function buildTable() {
  const rows = {};
  for (const [tool, r] of Object.entries(tools)) {
    rows[tool] = { art: r.art, face: r.face, glyph: r.glyph, verb: r.verb, tint: r.tint };
  }
  return `/* GENERATED by scripts/publish-robot-faces.mjs — do not edit.
   Source of truth: app/assets/tool-props.json, itself generated from the
   agent-playhouse skin. Run the script; never touch this file.

   Each row is one tool as the app knows it: which scene the robot appears in,
   the face he wears while doing it, and the VERB — what a human calls the
   thing, which is what gets lettered on the glass. "at the console", never
   "Bash". */
window.TD_FACES = {
  scenes: '/assets/robots/scenes/',
  props: '/assets/robots/props/',
  fallback: 'tile',
  tools: ${JSON.stringify(rows, null, 2).replace(/\n/g, '\n  ')},
};
`;
}

const stage = CHECK ? join(REPO, '.robot-faces-check') : OUT;
const stageScenes = CHECK ? join(stage, 'scenes') : OUT_SCENES;
const stageProps = CHECK ? join(stage, 'props') : OUT_PROPS;
const stageTable = CHECK ? join(stage, 'tool-faces.js') : OUT_TABLE;

mkdirSync(stageScenes, { recursive: true });
mkdirSync(stageProps, { recursive: true });

let copied = 0;
const absent = [];
for (const art of [...arts].sort()) {
  const scene = join(SRC_SCENES, `${art}.webp`);
  const prop = join(SRC_PROPS, `${art}.png`);
  if (!existsSync(scene) || !existsSync(prop)) { absent.push(art); continue; }
  copyFileSync(scene, join(stageScenes, `${art}.webp`));
  copyFileSync(prop, join(stageProps, `${art}.png`));
  copied += 1;
}
writeFileSync(stageTable, buildTable());

if (absent.length) {
  console.error(`no art in app/assets for: ${absent.join(', ')}`);
  console.error('run: node scripts/sync-tool-props.mjs');
  rmSync(stage, { recursive: true, force: true });
  process.exit(2);
}

/* A scene that is not animated is a bug that looks exactly like a working one:
   the card renders, the robot is there, and he simply never moves. Assert the
   frame count rather than trusting the copy. */
const still = [];
for (const f of readdirSync(stageScenes)) {
  const n = execFileSync('magick', ['identify', '-format', '%n\n', join(stageScenes, f)], {
    encoding: 'utf8',
  }).trim().split('\n')[0];
  if (Number(n) < 2) still.push(`${f} (${n} frame)`);
}
if (still.length) {
  console.error(`these scenes are not animated: ${still.join(', ')}`);
  rmSync(stage, { recursive: true, force: true });
  process.exit(2);
}

if (!CHECK) {
  console.log(`${copied} faces published to assets/robots/ (${Object.keys(tools).length} tool rows)`);
  process.exit(0);
}

// --check -------------------------------------------------------------------
// Straight byte comparison: this is a copy, not a render, so any difference is
// a real one and there is no tolerance to argue about.
const drift = [];
const cmp = (a, b, label) => {
  let x, y;
  try { x = readFileSync(a); } catch {}
  try { y = readFileSync(b); } catch {}
  if (!x || !y || !x.equals(y)) drift.push(label);
};
for (const f of readdirSync(stageScenes)) {
  cmp(join(stageScenes, f), join(OUT_SCENES, f), `assets/robots/scenes/${f}`);
}
for (const f of readdirSync(stageProps)) {
  cmp(join(stageProps, f), join(OUT_PROPS, f), `assets/robots/props/${f}`);
}
cmp(stageTable, OUT_TABLE, 'assets/robots/tool-faces.js');

/* A file the website still serves that the app no longer has is drift too, and
   it is the direction a plain copy never notices. */
for (const [dir, live] of [[stageScenes, OUT_SCENES], [stageProps, OUT_PROPS]]) {
  if (!existsSync(live)) continue;
  const want = new Set(readdirSync(dir));
  for (const f of readdirSync(live)) {
    if (!want.has(f)) drift.push(`assets/robots/${live.endsWith('scenes') ? 'scenes' : 'props'}/${f} (orphaned)`);
  }
}

rmSync(stage, { recursive: true, force: true });

if (drift.length) {
  console.error('the website\'s robot faces have drifted from the app:');
  for (const d of drift) console.error(`  ${d}`);
  console.error('run: node scripts/publish-robot-faces.mjs');
  process.exit(1);
}
console.log(`robot faces are in sync (${copied} scenes, ${copied} props)`);
