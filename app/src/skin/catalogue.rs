//! One versioned source map for skin authors. Proof is a separate, optional
//! capture receipt; source routing alone never certifies a native result.
use serde::{Deserialize, Serialize};

pub const SOURCE: &str = include_str!("../../skin-surfaces.json");

#[derive(Debug, Deserialize, Serialize)]
pub struct Catalogue {
    pub schema: String,
    pub fixtures: Vec<Fixture>,
    pub surfaces: Vec<Surface>,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct Fixture {
    pub id: String,
    pub environment: std::collections::BTreeMap<String, String>,
    pub action: Option<FixtureAction>,
}

#[derive(Debug, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum FixtureAction {
    Paint,
    Document,
    Bench,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct Surface {
    pub id: String,
    pub name: String,
    pub scope: String,
    pub owner: Owner,
    pub facets: Facets,
    pub policy: String,
    pub fixture: Option<String>,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct Owner {
    pub file: String,
    pub symbol: String,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct Facets {
    pub material: Route,
    pub boundary: Route,
    pub emphasis: Route,
    pub typography: Route,
    pub colour: Route,
}

#[derive(Clone, Copy, Debug, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Route {
    Skin,
    Mixed,
    Semantic,
    Content,
    Independent,
    NotApplicable,
    Unverified,
}

pub fn markdown() -> String {
    let catalogue: Catalogue = serde_json::from_str(SOURCE).expect("checked skin catalogue");
    let mut out = String::from("# Skin surface inventory\n\nGenerated by `terminal-delight skin --catalogue-md` from `app/skin-surfaces.json`. Edit that source.\n\nFacets describe source routing, not native certification. Capture receipts are separate and scoped to a build, skin, palette, geometry, grade and states. Missing proof is unverified. Content and semantic colours remain owned by their renderer.\n\n| Surface | Owner | Material | Boundary | Emphasis | Type | Colour | Fixture | Policy |\n|---|---|---|---|---|---|---|---|---|\n");
    for s in catalogue.surfaces {
        let f = s.facets;
        out.push_str(&format!(
            "| {} (`{}`) | `{}::{}` | {:?} | {:?} | {:?} | {:?} | {:?} | {} | {} |\n",
            s.name,
            s.id,
            s.owner.file,
            s.owner.symbol,
            f.material,
            f.boundary,
            f.emphasis,
            f.typography,
            f.colour,
            s.fixture.as_deref().unwrap_or("unavailable"),
            s.policy.replace('|', "/")
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{collections::HashSet, path::Path};

    #[test]
    fn catalogue_owners_and_fixture_references_still_exist() {
        let c: Catalogue = serde_json::from_str(SOURCE).unwrap();
        assert_eq!(c.schema, "td-skin-catalogue/1");
        let mut ids = HashSet::new();
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        for s in c.surfaces {
            assert!(ids.insert(s.id.clone()), "duplicate {}", s.id);
            let source = std::fs::read_to_string(root.join(&s.owner.file)).unwrap();
            assert!(
                source.contains(&s.owner.symbol),
                "stale owner {}: {}",
                s.id,
                s.owner.symbol
            );
            if let Some(fixture) = s.fixture {
                assert!(
                    c.fixtures.iter().any(|f| f.id == fixture),
                    "unknown fixture {fixture}"
                );
            }
            assert!(
                !s.policy.is_empty(),
                "{} needs a content/colour policy",
                s.id
            );
        }
    }
}
