//! The right-bar flyout's words: the chip beside the attention pill, the
//! panel's tabs, its `+` page, and the three kinds of tab (a repository's
//! changes, a file, a GitHub pull request).
//!
//! Written in-house with the rest of the table's conventions: keycaps
//! (`Ctrl+Shift+R`, `↵`), symbols, `git`, `gh` and product names stay as they
//! are, and every `{placeholder}` survives. English is the source of truth.

pub struct Flyout {
    /// The spine chip's tooltip heading.
    pub chip_tip: &'static str,
    /// The chip tooltip's second line. Keep the keycaps.
    pub chip_keys: &'static str,
    /// Help sheet row for Ctrl+Shift+R.
    pub help: &'static str,
    /// Right-click menu row on a code file or a pull request link.
    pub menu_open: &'static str,
    /// The `+` button's tooltip.
    pub new_tab: &'static str,
    /// A tab's ✕.
    pub close_tab: &'static str,
    /// The panel's own ✕.
    pub close_panel: &'static str,
    /// Heading of the `+` page.
    pub add_title: &'static str,
    /// The `+` page's first row. {repo} is a folder name.
    pub add_changes: &'static str,
    /// Under it.
    pub add_changes_sub: &'static str,
    /// When the task's terminal is not in a repository.
    pub add_no_repo: &'static str,
    /// The row for the pull request whose branch is checked out here.
    pub add_branch_pull: &'static str,
    /// Section heading.
    pub add_pulls: &'static str,
    pub add_no_pulls: &'static str,
    /// Section heading.
    pub add_files: &'static str,
    /// The finder's placeholder.
    pub add_filter: &'static str,
    pub add_no_files: &'static str,
    /// Foot of the `+` page. Keep the keycap.
    pub add_hint: &'static str,
    /// While git or gh is being asked.
    pub reading: &'static str,
    /// The Changes tab's two bases: everything this branch changed, or only
    /// what is not committed yet.
    pub base_branch: &'static str,
    pub base_uncommitted: &'static str,
    /// {rev} is a git ref such as origin/main or HEAD.
    pub against: &'static str,
    pub no_changes: &'static str,
    /// {count} files changed.
    pub changed: &'static str,
    /// A row for a folder git does not track yet.
    pub untracked_dir: &'static str,
    /// In place of a binary file's line counts.
    pub binary: &'static str,
    pub more_lines: &'static str,
    pub open_file: &'static str,
    pub refresh: &'static str,
    pub expand_all: &'static str,
    pub collapse_all: &'static str,
    /// {count} lines in a file.
    pub lines: &'static str,
    /// {size} is a size such as 8 MB.
    pub cut: &'static str,
    pub file_binary: &'static str,
    pub file_gone: &'static str,
    pub changed_lines: &'static str,
    /// A file git does not track yet.
    pub file_new: &'static str,
    pub pr_open: &'static str,
    pub pr_draft: &'static str,
    pub pr_merged: &'static str,
    pub pr_closed: &'static str,
    pub pr_unknown: &'static str,
    pub pr_overview: &'static str,
    pub pr_files: &'static str,
    pub pr_conversation: &'static str,
    /// {when} is an age or a date.
    pub pr_updated: &'static str,
    pub pr_checks: &'static str,
    pub pr_no_checks: &'static str,
    pub pr_reviewers: &'static str,
    pub pr_labels: &'static str,
    pub pr_none: &'static str,
    pub pr_description: &'static str,
    pub pr_no_description: &'static str,
    pub pr_no_comments: &'static str,
    pub pr_on_github: &'static str,
    pub pr_copy_checkout: &'static str,
    pub pr_copied: &'static str,
    pub pr_approved: &'static str,
    pub pr_changes_requested: &'static str,
    pub pr_review_required: &'static str,
    pub pr_conflicts: &'static str,
    pub pr_commits: &'static str,
    pub gh_missing: &'static str,
    /// Keep the command in backticks as it is.
    pub gh_signed_out: &'static str,
    pub not_repo: &'static str,
    pub no_github: &'static str,
    /// The panel's foot while it holds the keyboard. Keep the keys.
    pub keys: &'static str,
    /// The same, on the `+` page.
    pub keys_add: &'static str,
}

