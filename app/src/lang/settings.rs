//! Settings' words: the book's frame and nav, every page's name, and each
//! row's title and plain line.
//!
//! The page names and nav headings follow T3 Code's settings (Parker,
//! 2026-11-09: *"the section heading and names and glyphs will reflect what T3
//! code does"*), in each language's ordinary word for them. Section titles are
//! sentence case, as T3 writes them. A row's plain line says what the setting
//! does, in one sentence. Keycaps, `ssh`, `MCP` and file names stay as they
//! are, and every `{placeholder}` survives. English is the source of truth.

