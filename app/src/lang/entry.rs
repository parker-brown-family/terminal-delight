//! The entry point's words: the INBOX face of the left spine and the composer
//! that starts an agent from a sentence.
//!
//! Written in-house with the rest of the table's conventions: keycaps
//! (`Ctrl+Shift+E`, `↵`), symbols and product names stay as they are, and the
//! shelf names are short capitals because they sit in a 208-pixel spine.
//! English is the source of truth.

pub struct Entry {
    /// Left spine header toggle: the face that shows the project tree.
    pub spine_projects: &'static str,
    /// Left spine header toggle: the face that lists every agent as a conversation to close.
    pub spine_inbox: &'static str,
    /// Top shelf of the inbox: agents that want the person now. Parker's own words; keep it loud and short.
    pub shelf_look: &'static str,
    /// Folded shelf: agents mid-turn.
    pub shelf_working: &'static str,
    /// Folded shelf: agents the person put off until a time.
    pub shelf_snoozed: &'static str,
    /// Folded shelf: agents awake with nothing to say, frozen (resting) or ended with their conversation kept (asleep).
    pub shelf_quiet: &'static str,
    /// Folded shelf: agents the person marked done.
    pub shelf_done: &'static str,
    /// Under LOOK AT ME when it is empty.
    pub look_empty: &'static str,
    /// The whole inbox when no pane holds an agent. Keep the keycap.
    pub inbox_empty: &'static str,
    /// Row status: came back from a snooze, not yet visited.
    pub status_woke: &'static str,
    /// Row status on a snoozed row. {when} is a time, or a date and a time.
    pub status_until: &'static str,
    /// Row status on a done row. {when} is a time, or a date and a time.
    pub status_done_at: &'static str,
    /// Hover button on a row: put it off until a time.
    pub act_snooze: &'static str,
    /// Hover button on a row: mark it done.
    pub act_done: &'static str,
    /// Hover button on a snoozed row: bring it back now.
    pub act_wake: &'static str,
    /// Hover button on a done row: take it off the done shelf.
    pub act_reopen: &'static str,
    /// Heading of the snooze menu.
    pub snooze_title: &'static str,
    /// Snooze choice.
    pub wake_hour: &'static str,
    /// Snooze choice.
    pub wake_three: &'static str,
    /// Snooze choice: six this evening.
    pub wake_evening: &'static str,
    /// Snooze choice: nine tomorrow.
    pub wake_morning: &'static str,
    /// Snooze choice: nine next Monday.
    pub wake_monday: &'static str,
    /// Button in the spine header that opens the composer.
    pub new_chat: &'static str,
    /// The composer's heading, a question to the person.
    pub composer_title: &'static str,
    /// Under the heading: what pressing Enter will do, and that nothing else stops.
    pub composer_sub: &'static str,
    /// Inside the empty text box.
    pub composer_placeholder: &'static str,
    /// Key hint line under the chips. Keep the keycaps and the dots.
    pub composer_hint: &'static str,
    /// Chip header: which machine the agent starts on.
    pub composer_machine: &'static str,
    /// Button beside a far machine: open its screen in gliff.
    pub composer_screen: &'static str,
    /// Shown after Ctrl+Enter. {name} is the new tab's name.
    pub composer_started: &'static str,
    /// The PROJECT chip's first choice: no project yet. The agent starts in
    /// the home folder and its tab is filed under no project.
    pub project_none: &'static str,
    /// Shown when machines.toml cannot be read. {error} is the reader's message.
    pub composer_machines_error: &'static str,
    /// Under the chips when a far machine is chosen. {machine} is its name.
    pub composer_far_note: &'static str,
    /// Inside the PROJECT chip while it has the keyboard and nothing is typed.
    pub composer_filter: &'static str,
    /// Shown when gliff could not be started. {error} is the system's message.
    pub composer_screen_failed: &'static str,
    /// Help sheet row: what Ctrl+Shift+I does.
    pub help_inbox: &'static str,
    /// Help sheet row: what Ctrl+Shift+E does.
    pub help_composer: &'static str,
    /// Under LOOK AT ME, the order it is in now; a press switches. The rail's order: whoever has waited longest first.
    pub order_rail: &'static str,
    /// Under LOOK AT ME, the order it is in now; a press switches. T3's order: whoever came back most recently first.
    pub order_returned: &'static str,
    /// Shown when the custom local runner is chosen with a far machine. {machine} is the far machine's name.
    pub composer_far_local: &'static str,
    /// Dialog opened by dropping a pane or tab onto another tab: its heading.
    pub relate_title: &'static str,
    /// Under the heading: what the dialog decides.
    pub relate_sub: &'static str,
    /// What the SEE line lets the first agent do to the second.
    pub relate_see: &'static str,
    /// What the READ line lets the first agent do to the second.
    pub relate_read: &'static str,
    /// What the ASK line lets the first agent do to the second.
    pub relate_ask: &'static str,
    /// What the PROMPT line lets the first agent do to the second.
    pub relate_prompt: &'static str,
    /// Beside the line already drawn between them. {rung} is its verb.
    pub relate_now: &'static str,
    /// Button: turn the relationship round.
    pub relate_swap: &'static str,
    /// Button: draw the line.
    pub relate_save: &'static str,
    /// Button: close the dialog, drawing nothing.
    pub relate_cancel: &'static str,
    /// Button, only after a PANE was dropped: the old landing, moving it into the tab.
    pub relate_move: &'static str,
    /// The dialog's keys.
    pub relate_hint: &'static str,
    /// Shown when the two are in different orgs on the Threshing Floor.
    pub relate_split: &'static str,
    /// Shown when the dialog is asked to draw before a verb is picked.
    pub relate_none: &'static str,
    /// Drag chip over the middle of another tab's row. {name} is that tab.
    pub drag_relate: &'static str,
}

