//! Words for other machines: the window that shows another machine's
//! Terminal Delight, the Machines page in Settings, and far agents on the
//! Threshing Floor.
//!
//! Written in-house with the rest of the table's conventions: keycaps, `ssh`,
//! file names and product names stay as they are, and every `{placeholder}`
//! survives. English is the source of truth.

pub struct Far {
    /// The banner when a far machine answers again. {machine} is its name in capitals.
    pub back: &'static str,
    /// The strip across a far window while its machine does not answer.
    pub down: &'static str,
    /// Under it: what became of the terminals. They are not ended.
    pub down_held: &'static str,
    /// When the far machine has started a new session host. {machine} in capitals.
    pub replaced: &'static str,
    /// Under it. What this window shows is no longer what runs there.
    pub replaced_sub: &'static str,
    /// Tooltip on the chip that names the machine a far window shows. {machine} as written in machines.toml, {dest} is the ssh destination.
    pub chip_tip: &'static str,
    /// Heading of the Threshing Floor's section for agents on other machines.
    pub floor_title: &'static str,
    /// When machines.toml lists no machine.
    pub floor_none: &'static str,
    /// Label before the chips that choose which local seat's lines are being edited.
    pub floor_from: &'static str,
    /// When no agent here is seated, so no line can start.
    pub floor_no_seat: &'static str,
    /// While a machine is being asked and has never answered.
    pub floor_asking: &'static str,
    /// How long ago a machine last answered. {age} is like 4s or 2m.
    pub floor_heard: &'static str,
    /// A machine that could not be asked. The reason follows on its own line.
    pub floor_unreachable: &'static str,
    /// A machine that answered and shows this one no agent. {machine} is its name here, {me} is this machine's own name.
    pub floor_shares_nothing: &'static str,
    /// A machine whose windows have agent access switched off.
    pub floor_mcp_off: &'static str,
    /// A machine that shares, with no agent running.
    pub floor_no_agents: &'static str,
    /// Agents there that nothing durable names. {count} is a number.
    pub floor_unnamed: &'static str,
    /// The chip on a far agent that no line from the chosen seat reaches.
    pub floor_no_line: &'static str,
    /// Beside a line that asks for more than the far machine allows. {rung} is a rung word.
    pub floor_allows: &'static str,
    /// A machine whose Terminal Delight does not know the question.
    pub floor_old_build: &'static str,
    /// Tooltip on the button that asks every machine again.
    pub floor_refresh: &'static str,
    /// Settings section heading: this machine.
    pub st_this: &'static str,
    /// Row title: the name other machines know this one by.
    pub st_name: &'static str,
    /// Under it. Keep TD_MACHINE_NAME as written.
    pub st_name_sub: &'static str,
    /// A machine's status line while it is being asked.
    pub st_asking: &'static str,
    /// A machine's status line. {version} is a number like 0.5.3.
    pub st_td: &'static str,
    /// A machine that answered and has no Terminal Delight.
    pub st_no_td: &'static str,
    /// Appended to a machine's status line when it is on a tailnet.
    pub st_tailscale: &'static str,
    /// Row title for one session on a far machine. {key} is its name.
    pub st_session: &'static str,
    /// Under a session a window on the far machine is showing.
    pub st_session_window: &'static str,
    /// Under a session nobody on the far machine is watching.
    pub st_session_idle: &'static str,
    /// Under a session whose state the far machine did not say.
    pub st_session_unknown: &'static str,
    /// The button that opens a far session in a window on this machine.
    pub st_open_here: &'static str,
    /// A machine with Terminal Delight and no session running.
    pub st_no_session: &'static str,
    /// Row title: how far that machine's agents may reach into this one.
    pub st_sharing: &'static str,
    /// Under it. The rung words stay in order.
    pub st_sharing_sub: &'static str,
    /// Where the sharing chips would be, for a machine that has not answered yet.
    pub st_sharing_unknown: &'static str,
    /// The first sharing chip: share nothing.
    pub st_nothing: &'static str,
    /// Section heading: machines that asked and were shown nothing.
    pub st_asked: &'static str,
    /// Under a machine that asked. It was shown nothing.
    pub st_asked_sub: &'static str,
    /// When no machine is listed.
    pub st_none: &'static str,
    /// Under it. Keep ssh as written.
    pub st_none_sub: &'static str,
    /// Shown briefly after Open here is pressed. {machine} in capitals.
    pub st_opening: &'static str,
    /// A pane header's state word when the terminal is being shown in another window. One short word, beside live / done / exited.
    pub elsewhere: &'static str,
    /// Under the sharing chips when this window's agent access switch is off, so nothing set there takes effect.
    pub st_mcp_off: &'static str,
}

